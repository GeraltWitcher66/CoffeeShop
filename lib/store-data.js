export function productsInCategory(categoryId) {
  return products.filter((product) => product.categoryId === categoryId);
}

export function findProduct(id) {
  return products.find((product) => product.id === id) ?? null;
}

export function isInStock(product) {
  return (product?.stock ?? 0) > 0;
}

export function relatedProducts(product, limit = 4) {
  if (!product) return [];
  const siblings = productsInCategory(product.categoryId).filter((item) => item.id !== product.id);
  const others = products.filter(
    (item) => item.id !== product.id && item.categoryId !== product.categoryId
  );
  return [...siblings, ...others].slice(0, limit);
}
